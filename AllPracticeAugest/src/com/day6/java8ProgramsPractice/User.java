public class User {

	private Integer id;
	
	private String name;
	
	private String email;
	
	private String mobileNo;
	
	private String gender;
	
	private String city;

	@Override
	public String toString() {
		return "User [id=" + id + ", name=" + name + ", email=" + email + ", mobileNo=" + mobileNo + ", gender="
				+ gender + ", city=" + city + "]";
	}
	
	
	
	
	
}
