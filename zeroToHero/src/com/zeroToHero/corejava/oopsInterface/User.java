package com.zeroToHero.corejava.oopsInterface;

public class User {

	private Integer id;
	
	private String anme;
	
	private String mobileNo;
	
	private String email;
	
	private String city;

	public User(Integer id, String anme, String mobileNo, String email, String city) {
		super();
		this.id = id;
		this.anme = anme;
		this.mobileNo = mobileNo;
		this.email = email;
		this.city = city;
	}
	
	
}
