package com.day27.java8ProgramsPractice;

public class EmployeeStream {

	private Integer id;
	
	private String name;
	
	private String dept;
	
	private Double salary;

	public EmployeeStream(Integer id, String name, String dept, Double salary) {
		super();
		this.id = id;
		this.name = name;
		this.dept = dept;
		this.salary = salary;
	}
	
	
}
