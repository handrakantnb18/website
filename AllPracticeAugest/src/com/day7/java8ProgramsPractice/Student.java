package com.day7.java8ProgramsPractice;

public class Student {

	private Integer id;
	
	private String name;
	
	private String email;
	
	private String cource;
	
	private String city;
	
	private Double fees;
	
	private String dept;

	@Override
	public String toString() {
		return "Student [id=" + id + ", name=" + name + ", email=" + email + ", cource=" + cource + ", city=" + city
				+ ", fees=" + fees + ", dept=" + dept + "]";
	}
	
	
}
