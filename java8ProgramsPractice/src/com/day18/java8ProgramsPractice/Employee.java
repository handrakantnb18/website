package com.day18.java8ProgramsPractice;

public class Employee {

	private Integer id;
	
	private String name;
	
	private String dept;
	
	private String email;
	
	private String mobileNo;

	@Override
	public String toString() {
		return "Employee [id=" + id + ", name=" + name + ", dept=" + dept + ", email=" + email + ", mobileNo="
				+ mobileNo + "]";
	}
	
	
	
}
