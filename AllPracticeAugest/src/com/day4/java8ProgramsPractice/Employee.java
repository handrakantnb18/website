package com.day4.java8ProgramsPractice;

public class Employee {

	private Integer id;
	
	private String name;
	
	private String city;
	
	private String mobile;
	
	private String email;
	
	private String dept;

	@Override
	public String toString() {
		return "Employee [id=" + id + ", name=" + name + ", city=" + city + ", mobile=" + mobile + ", email=" + email
				+ ", dept=" + dept + "]";
	}
	
	
}
