package com.day7.java;

public class Customer {

	private Integer bid;

	private String name;

	private Double balance;

	private String branch;

	private String city;

	private String accountType;

	@Override
	public String toString() {
		return "Customer [bid=" + bid + ", name=" + name + ", balance=" + balance + ", branch=" + branch + ", city="
				+ city + ", accountType=" + accountType + "]";
	}

	
	
	
}
